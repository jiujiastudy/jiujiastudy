def slogan_for(week):
    """周报顶上的口号：按 ISO 周轮换，一周一句。week 可以是 '2026-W38' 或整数。"""
    try:
        n = int(str(week).upper().split("-W")[-1])
    except ValueError:
        n = 0
    return SLOGANS[n % len(SLOGANS)]
